#!/usr/bin/env node
// Regenerates src/data/countries.generated.ts from Wikidata.
//
// The ISO numeric code (P299) is the join key: world-atlas TopoJSON uses it as
// each country's feature id, while the rest of the app speaks alpha-2 (P297).
// Run this only if ISO 3166-1 changes — which is roughly never.
//
//   node scripts/build-countries.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const QUERY = `SELECT ?c ?cLabel ?a2 ?num WHERE {
  ?c wdt:P299 ?num . ?c wdt:P297 ?a2 .
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en". }
}`;

const res = await fetch(
  `https://query.wikidata.org/sparql?query=${encodeURIComponent(QUERY)}`,
  {
    headers: {
      Accept: "application/sparql-results+json",
      // WDQS rejects generic user agents outright.
      "User-Agent": "bookmappy/0.1 (https://github.com/ihrynkiv/bookmappy)",
    },
  },
);
if (!res.ok) throw new Error(`Wikidata returned ${res.status}`);

const byQid = {};
const byA2 = {};
for (const row of (await res.json()).results.bindings) {
  const qid = row.c.value.split("/").pop();
  const a2 = row.a2.value.toUpperCase();
  const name = row.cLabel.value;
  if (/^Q\d+$/.test(name)) continue; // unlabelled item
  if (byA2[a2]) continue; // first result wins
  byQid[qid] = a2;
  byA2[a2] = { name, num: row.num.value.padStart(3, "0") };
}

const lines = [
  "// AUTO-GENERATED by scripts/build-countries.mjs from Wikidata (P297/P299). Do not edit by hand.",
  "",
  "/** ISO 3166-1 alpha-2 -> display name + numeric code (numeric = TopoJSON feature id). */",
  "export const COUNTRIES: Record<string, { name: string; num: string }> = {",
  ...Object.keys(byA2)
    .sort()
    .map((k) => `  ${k}: { name: ${JSON.stringify(byA2[k].name)}, num: "${byA2[k].num}" },`),
  "};",
  "",
  "/** Wikidata QID -> ISO alpha-2, for every present-day country carrying an ISO code. */",
  "export const QID_TO_ISO: Record<string, string> = {",
  ...Object.keys(byQid)
    .sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)))
    .map((k) => `  ${k}: "${byQid[k]}",`),
  "};",
];

const out = fileURLToPath(new URL("../src/data/countries.generated.ts", import.meta.url));
writeFileSync(out, lines.join("\n") + "\n");
console.log(`Wrote ${Object.keys(byA2).length} countries to ${out}`);
